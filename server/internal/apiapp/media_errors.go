func publicMediaErrorCode(message string) string {
	if message == "" {
		return ""
	}
	code := strings.SplitN(message, ":", 2)[0]
	if publicMediaErrorCodes[code] {
		return code
	}
	if strings.HasPrefix(code, "provider_http_") {
		if status, err := strconv.Atoi(strings.TrimPrefix(code, "provider_http_")); err == nil && status >= 400 && status <= 599 {
			return code
		}
	}
	return "media_operation_failed"
}
